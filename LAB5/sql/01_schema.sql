IF DB_ID(N'QuanLyDuLich') IS NOT NULL
BEGIN
    ALTER DATABASE QuanLyDuLich SET SINGLE_USER WITH ROLLBACK IMMEDIATE;
    DROP DATABASE QuanLyDuLich;
END
GO
CREATE DATABASE QuanLyDuLich;
GO
USE QuanLyDuLich;
GO

CREATE TABLE Tour (
    MaTour VARCHAR(10) NOT NULL PRIMARY KEY,
    TenTour NVARCHAR(100) NOT NULL,
    SoNgay INT NOT NULL,
    SoDem INT NOT NULL,
    DonGiaKhach DECIMAL(18,0) NOT NULL,
    TienCongHDV DECIMAL(18,0) NOT NULL,
    CONSTRAINT CK_Tour CHECK (SoNgay >= 1 AND SoDem >= 0 AND DonGiaKhach >= 0)
);

CREATE TABLE PhuongTien (
    MaPT VARCHAR(10) NOT NULL PRIMARY KEY,
    TenPT NVARCHAR(100) NOT NULL
);

CREATE TABLE DiemDung (
    MaDiemDung VARCHAR(10) NOT NULL PRIMARY KEY,
    TenDiemDung NVARCHAR(100) NOT NULL,
    ThuTu INT NOT NULL,
    DoiPhuongTien BIT NOT NULL,
    CoAnUong BIT NOT NULL,
    CoKhachSan BIT NOT NULL,
    SoSaoKhachSan INT NOT NULL,
    MaTour VARCHAR(10) NOT NULL,
    MaPT VARCHAR(10) NOT NULL,
    CONSTRAINT FK_DiemDung_MaTour FOREIGN KEY (MaTour) REFERENCES Tour(MaTour) ON DELETE CASCADE,
    CONSTRAINT FK_DiemDung_MaPT FOREIGN KEY (MaPT) REFERENCES PhuongTien(MaPT),
    CONSTRAINT CK_DiemDung_Sao CHECK (SoSaoKhachSan IN (0,2,3,4,5) AND (CoKhachSan = 1 OR SoSaoKhachSan = 0))
);

CREATE TABLE DiemThamQuan (
    MaDTQ VARCHAR(10) NOT NULL PRIMARY KEY,
    TenDTQ NVARCHAR(100) NOT NULL,
    DiaDiem NVARCHAR(200) NULL,
    NoiDung NVARCHAR(200) NULL,
    YNghia NVARCHAR(200) NULL
);

CREATE TABLE NhanVien (
    MaNV VARCHAR(10) NOT NULL PRIMARY KEY,
    HoTen NVARCHAR(100) NOT NULL,
    DienThoai VARCHAR(15) NULL,
    ChucVu NVARCHAR(100) NOT NULL,
    LuongCoBan DECIMAL(18,0) NOT NULL
);

CREATE TABLE ChuyenDi (
    MaChuyen VARCHAR(10) NOT NULL PRIMARY KEY,
    NgayDi DATE NOT NULL,
    NgayVe DATE NOT NULL,
    DiaDiemDon NVARCHAR(200) NULL,
    MaTour VARCHAR(10) NOT NULL,
    MaNV VARCHAR(10) NULL,
    CONSTRAINT FK_ChuyenDi_MaTour FOREIGN KEY (MaTour) REFERENCES Tour(MaTour),
    CONSTRAINT FK_ChuyenDi_MaNV FOREIGN KEY (MaNV) REFERENCES NhanVien(MaNV),
    CONSTRAINT CK_Chuyen_Ngay CHECK (NgayVe >= NgayDi)
);

CREATE TABLE KhachHang (
    MaKH VARCHAR(10) NOT NULL PRIMARY KEY,
    LoaiKhachHang VARCHAR(20) NOT NULL CHECK (LoaiKhachHang IN ('KHACHLE','KHACHDOAN')),
    HoTen NVARCHAR(100) NULL,
    DiaChi NVARCHAR(200) NULL,
    DienThoai VARCHAR(15) NULL,
    TenCoQuan NVARCHAR(100) NULL,
    NguoiDaiDien NVARCHAR(100) NULL,
    CONSTRAINT CK_KhachHang_Loai CHECK ((LoaiKhachHang = 'KHACHLE' AND HoTen IS NOT NULL) OR (LoaiKhachHang = 'KHACHDOAN' AND TenCoQuan IS NOT NULL))
);

CREATE TABLE PhieuDangKyChuyen (
    MaPhieuLe VARCHAR(10) NOT NULL PRIMARY KEY,
    NgayDangKy DATE NOT NULL,
    SoNguoi INT NOT NULL,
    DiaDiemDon NVARCHAR(200) NOT NULL,
    SoTien DECIMAL(18,0) NOT NULL,
    MaKH VARCHAR(10) NOT NULL,
    MaChuyen VARCHAR(10) NOT NULL,
    CONSTRAINT FK_PhieuDangKyChuyen_MaKH FOREIGN KEY (MaKH) REFERENCES KhachHang(MaKH),
    CONSTRAINT FK_PhieuDangKyChuyen_MaChuyen FOREIGN KEY (MaChuyen) REFERENCES ChuyenDi(MaChuyen),
    CONSTRAINT CK_Le_SoNguoi CHECK (SoNguoi BETWEEN 1 AND 12)
);

CREATE TABLE PhieuDangKyDoan (
    MaPhieuDoan VARCHAR(10) NOT NULL PRIMARY KEY,
    NgayDangKy DATE NOT NULL,
    NgayDi DATE NOT NULL,
    SoNguoi INT NOT NULL,
    DiaDiemDon NVARCHAR(200) NULL,
    TienCoc DECIMAL(18,0) NOT NULL,
    CoBaoHiem BIT NOT NULL,
    TrangThai NVARCHAR(30) NOT NULL,
    MaKH VARCHAR(10) NOT NULL,
    MaTour VARCHAR(10) NOT NULL,
    CONSTRAINT FK_PhieuDangKyDoan_MaKH FOREIGN KEY (MaKH) REFERENCES KhachHang(MaKH),
    CONSTRAINT FK_PhieuDangKyDoan_MaTour FOREIGN KEY (MaTour) REFERENCES Tour(MaTour),
    CONSTRAINT CK_Doan_SoNguoi CHECK (SoNguoi > 12),
    CONSTRAINT CK_Doan_Coc CHECK (TienCoc >= 0)
);

CREATE TABLE NguoiDiCung (
    MaNguoi VARCHAR(10) NOT NULL PRIMARY KEY,
    HoTen NVARCHAR(100) NOT NULL,
    NgaySinh DATE NULL,
    SoCMND VARCHAR(15) NULL,
    MaPhieuDoan VARCHAR(10) NOT NULL,
    CONSTRAINT FK_NguoiDiCung_MaPhieuDoan FOREIGN KEY (MaPhieuDoan) REFERENCES PhieuDangKyDoan(MaPhieuDoan) ON DELETE CASCADE
);

CREATE TABLE PhieuThanhToanDoan (
    MaTT VARCHAR(10) NOT NULL PRIMARY KEY,
    NgayThanhToan DATE NOT NULL,
    SoTien DECIMAL(18,0) NOT NULL,
    Loai NVARCHAR(30) NOT NULL,
    MaPhieuDoan VARCHAR(10) NOT NULL,
    CONSTRAINT FK_PhieuThanhToanDoan_MaPhieuDoan FOREIGN KEY (MaPhieuDoan) REFERENCES PhieuDangKyDoan(MaPhieuDoan)
);

CREATE TABLE PhanCongDoan (
    MaPC VARCHAR(10) NOT NULL PRIMARY KEY,
    VaiTro NVARCHAR(100) NOT NULL,
    MaPhieuDoan VARCHAR(10) NOT NULL,
    MaNV VARCHAR(10) NOT NULL,
    CONSTRAINT FK_PhanCongDoan_MaPhieuDoan FOREIGN KEY (MaPhieuDoan) REFERENCES PhieuDangKyDoan(MaPhieuDoan) ON DELETE CASCADE,
    CONSTRAINT FK_PhanCongDoan_MaNV FOREIGN KEY (MaNV) REFERENCES NhanVien(MaNV),
    CONSTRAINT UQ_PhanCong UNIQUE (MaPhieuDoan, MaNV)
);

CREATE TABLE LuongThang (
    MaLuong VARCHAR(10) NOT NULL PRIMARY KEY,
    Thang INT NOT NULL,
    Nam INT NOT NULL,
    LuongCoBan DECIMAL(18,0) NOT NULL,
    LuongTheoTour DECIMAL(18,0) NOT NULL,
    TongLuong DECIMAL(18,0) NOT NULL,
    MaNV VARCHAR(10) NOT NULL,
    CONSTRAINT FK_LuongThang_MaNV FOREIGN KEY (MaNV) REFERENCES NhanVien(MaNV),
    CONSTRAINT UQ_Luong UNIQUE (MaNV, Thang, Nam)
);

CREATE TABLE PhieuKhaoSat (
    MaPKS VARCHAR(10) NOT NULL PRIMARY KEY,
    NgayGui DATE NOT NULL,
    DiemHaiLong INT NOT NULL,
    GopY NVARCHAR(200) NULL,
    MaKH VARCHAR(10) NOT NULL,
    MaChuyen VARCHAR(10) NULL,
    MaPhieuDoan VARCHAR(10) NULL,
    CONSTRAINT FK_PhieuKhaoSat_MaKH FOREIGN KEY (MaKH) REFERENCES KhachHang(MaKH),
    CONSTRAINT FK_PhieuKhaoSat_MaChuyen FOREIGN KEY (MaChuyen) REFERENCES ChuyenDi(MaChuyen),
    CONSTRAINT FK_PhieuKhaoSat_MaPhieuDoan FOREIGN KEY (MaPhieuDoan) REFERENCES PhieuDangKyDoan(MaPhieuDoan),
    CONSTRAINT CK_KhaoSat_Nguon CHECK ((MaChuyen IS NULL AND MaPhieuDoan IS NOT NULL) OR (MaChuyen IS NOT NULL AND MaPhieuDoan IS NULL)),
    CONSTRAINT CK_KhaoSat_Diem CHECK (DiemHaiLong IS NULL OR DiemHaiLong BETWEEN 1 AND 5)
);

CREATE TABLE Tour_DiemThamQuan (
    MaTour VARCHAR(10) NOT NULL REFERENCES Tour(MaTour),
    MaDTQ VARCHAR(10) NOT NULL REFERENCES DiemThamQuan(MaDTQ),
    PRIMARY KEY (MaTour, MaDTQ)
);

GO