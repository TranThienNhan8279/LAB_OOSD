IF DB_ID(N'QuanLyNhanSu') IS NOT NULL
BEGIN
    ALTER DATABASE QuanLyNhanSu SET SINGLE_USER WITH ROLLBACK IMMEDIATE;
    DROP DATABASE QuanLyNhanSu;
END
GO
CREATE DATABASE QuanLyNhanSu;
GO
USE QuanLyNhanSu;
GO

CREATE TABLE PhongBan (
    MaPB VARCHAR(10) NOT NULL PRIMARY KEY,
    TenPB NVARCHAR(100) NOT NULL
);

CREATE TABLE NhanVien (
    MaNV VARCHAR(10) NOT NULL PRIMARY KEY,
    HoTen NVARCHAR(100) NOT NULL,
    NgaySinh DATE NOT NULL,
    DiaChi NVARCHAR(200) NULL,
    DienThoai VARCHAR(15) NULL,
    TrangThai NVARCHAR(30) NOT NULL,
    MaPB VARCHAR(10) NOT NULL,
    CONSTRAINT FK_NhanVien_MaPB FOREIGN KEY (MaPB) REFERENCES PhongBan(MaPB),
    CONSTRAINT CK_NV_TT CHECK (TrangThai IN (N'Thử việc', N'Chính thức', N'Đã nghỉ'))
);

CREATE TABLE QuyetDinhTuyenDung (
    MaQDTD VARCHAR(10) NOT NULL PRIMARY KEY,
    NgayQD DATE NOT NULL,
    NgayBatDauThuViec DATE NOT NULL,
    NgayKetThucThuViec DATE NOT NULL,
    LuongThuViec DECIMAL(18,0) NOT NULL,
    DieuKhoan NVARCHAR(200) NULL,
    MaNV VARCHAR(10) NOT NULL,
    CONSTRAINT FK_QuyetDinhTuyenDung_MaNV FOREIGN KEY (MaNV) REFERENCES NhanVien(MaNV),
    CONSTRAINT UQ_QuyetDinhTuyenDung_MaNV UNIQUE (MaNV),
    CONSTRAINT CK_QDTD_Ngay CHECK (NgayKetThucThuViec >= NgayBatDauThuViec),
    CONSTRAINT CK_QDTD_Luong CHECK (LuongThuViec >= 0)
);

CREATE TABLE HopDong (
    MaHD VARCHAR(10) NOT NULL PRIMARY KEY,
    LoaiHD NVARCHAR(30) NOT NULL,
    NgayKy DATE NOT NULL,
    NgayBatDau DATE NOT NULL,
    NgayKetThuc DATE NULL,
    LuongHopDong DECIMAL(18,0) NOT NULL,
    MaNV VARCHAR(10) NOT NULL,
    CONSTRAINT FK_HopDong_MaNV FOREIGN KEY (MaNV) REFERENCES NhanVien(MaNV),
    CONSTRAINT CK_HD_Loai CHECK (LoaiHD IN (N'Ngắn hạn', N'Dài hạn')),
    CONSTRAINT CK_HD_NgayKT CHECK ((LoaiHD = N'Ngắn hạn' AND NgayKetThuc IS NOT NULL AND NgayKetThuc > NgayBatDau) OR (LoaiHD = N'Dài hạn' AND NgayKetThuc IS NULL)),
    CONSTRAINT CK_HD_Luong CHECK (LuongHopDong > 0)
);

CREATE TABLE ChucVu (
    MaCV VARCHAR(10) NOT NULL PRIMARY KEY,
    TenCV NVARCHAR(100) NOT NULL,
    PhuCap DECIMAL(18,0) NOT NULL,
    CONSTRAINT CK_CV_PhuCap CHECK (PhuCap >= 0)
);

CREATE TABLE QuyetDinhChucVu (
    MaQDCV VARCHAR(10) NOT NULL PRIMARY KEY,
    NgayQD DATE NOT NULL,
    NgayHieuLuc DATE NOT NULL,
    MaCV VARCHAR(10) NOT NULL,
    MaNV VARCHAR(10) NOT NULL,
    CONSTRAINT FK_QuyetDinhChucVu_MaCV FOREIGN KEY (MaCV) REFERENCES ChucVu(MaCV),
    CONSTRAINT FK_QuyetDinhChucVu_MaNV FOREIGN KEY (MaNV) REFERENCES NhanVien(MaNV)
);

CREATE TABLE QuyetDinhLuong (
    MaQDL VARCHAR(10) NOT NULL PRIMARY KEY,
    NgayQD DATE NOT NULL,
    NgayHieuLuc DATE NOT NULL,
    LuongMoi DECIMAL(18,0) NOT NULL,
    MaNV VARCHAR(10) NOT NULL,
    CONSTRAINT FK_QuyetDinhLuong_MaNV FOREIGN KEY (MaNV) REFERENCES NhanVien(MaNV),
    CONSTRAINT CK_QDL_Luong CHECK (LuongMoi > 0)
);

CREATE TABLE BaoHiem (
    MaBH VARCHAR(10) NOT NULL PRIMARY KEY,
    SoSo NVARCHAR(100) NOT NULL,
    NgayThamGia DATE NOT NULL,
    TyLeTrich DECIMAL(6,4) NOT NULL,
    MaHD VARCHAR(10) NOT NULL,
    CONSTRAINT FK_BaoHiem_MaHD FOREIGN KEY (MaHD) REFERENCES HopDong(MaHD),
    CONSTRAINT UQ_BaoHiem_MaHD UNIQUE (MaHD),
    CONSTRAINT CK_BH_TyLe CHECK (TyLeTrich > 0 AND TyLeTrich < 1)
);

CREATE TABLE KeHoachTuan (
    MaKHT VARCHAR(10) NOT NULL PRIMARY KEY,
    TuanBatDau DATE NOT NULL,
    GhiChu NVARCHAR(200) NULL,
    MaPB VARCHAR(10) NOT NULL,
    CONSTRAINT FK_KeHoachTuan_MaPB FOREIGN KEY (MaPB) REFERENCES PhongBan(MaPB),
    CONSTRAINT UQ_KHT UNIQUE (MaPB, TuanBatDau)
);

CREATE TABLE ChiTietPhanCong (
    MaCTPC VARCHAR(10) NOT NULL PRIMARY KEY,
    NgayLam DATE NOT NULL,
    CaLam NVARCHAR(30) NOT NULL,
    CongViec NVARCHAR(200) NULL,
    MaKHT VARCHAR(10) NOT NULL,
    MaNV VARCHAR(10) NOT NULL,
    CONSTRAINT FK_ChiTietPhanCong_MaKHT FOREIGN KEY (MaKHT) REFERENCES KeHoachTuan(MaKHT) ON DELETE CASCADE,
    CONSTRAINT FK_ChiTietPhanCong_MaNV FOREIGN KEY (MaNV) REFERENCES NhanVien(MaNV),
    CONSTRAINT CK_CTPC_Ca CHECK (CaLam IN (N'Sáng', N'Chiều', N'Tối')),
    CONSTRAINT UQ_CTPC UNIQUE (MaNV, NgayLam, CaLam)
);

CREATE TABLE PhieuChamCong (
    MaPCC VARCHAR(10) NOT NULL PRIMARY KEY,
    Ngay DATE NOT NULL,
    SoGioLam DECIMAL(5,2) NOT NULL,
    MaNV VARCHAR(10) NOT NULL,
    CONSTRAINT FK_PhieuChamCong_MaNV FOREIGN KEY (MaNV) REFERENCES NhanVien(MaNV),
    CONSTRAINT CK_PCC_Gio CHECK (SoGioLam >= 0 AND SoGioLam <= 24),
    CONSTRAINT UQ_PCC UNIQUE (MaNV, Ngay)
);

CREATE TABLE PhieuPhuTroi (
    MaPPT VARCHAR(10) NOT NULL PRIMARY KEY,
    Ngay DATE NOT NULL,
    HeSo DECIMAL(5,2) NOT NULL,
    MaPB VARCHAR(10) NOT NULL,
    CONSTRAINT FK_PhieuPhuTroi_MaPB FOREIGN KEY (MaPB) REFERENCES PhongBan(MaPB),
    CONSTRAINT CK_PPT_HeSo CHECK (HeSo >= 1.5)
);

CREATE TABLE ChiTietPhuTroi (
    MaCTPT VARCHAR(10) NOT NULL PRIMARY KEY,
    SoGio DECIMAL(5,2) NOT NULL,
    MaPPT VARCHAR(10) NOT NULL,
    MaNV VARCHAR(10) NOT NULL,
    CONSTRAINT FK_ChiTietPhuTroi_MaPPT FOREIGN KEY (MaPPT) REFERENCES PhieuPhuTroi(MaPPT) ON DELETE CASCADE,
    CONSTRAINT FK_ChiTietPhuTroi_MaNV FOREIGN KEY (MaNV) REFERENCES NhanVien(MaNV),
    CONSTRAINT CK_CTPT_Gio CHECK (SoGio > 0 AND SoGio <= 4),
    CONSTRAINT UQ_CTPT UNIQUE (MaPPT, MaNV)
);

CREATE TABLE QuyetDinhKhenThuong (
    MaKT VARCHAR(10) NOT NULL PRIMARY KEY,
    NgayQD DATE NOT NULL,
    LoaiKT NVARCHAR(30) NOT NULL,
    NoiDung NVARCHAR(200) NULL,
    SoTien DECIMAL(18,0) NOT NULL,
    MaNV VARCHAR(10) NULL,
    MaPB VARCHAR(10) NULL,
    CONSTRAINT FK_QuyetDinhKhenThuong_MaNV FOREIGN KEY (MaNV) REFERENCES NhanVien(MaNV),
    CONSTRAINT FK_QuyetDinhKhenThuong_MaPB FOREIGN KEY (MaPB) REFERENCES PhongBan(MaPB),
    CONSTRAINT CK_KT_Loai CHECK (LoaiKT IN (N'Cá nhân', N'Tập thể')),
    CONSTRAINT CK_KT_Tien CHECK (SoTien > 0),
    CONSTRAINT CK_KT_DoiTuong CHECK ((LoaiKT = N'Cá nhân' AND MaNV IS NOT NULL AND MaPB IS NULL) OR (LoaiKT = N'Tập thể' AND MaPB IS NOT NULL AND MaNV IS NULL))
);

CREATE TABLE PhieuChi (
    MaPC VARCHAR(10) NOT NULL PRIMARY KEY,
    NgayChi DATE NOT NULL,
    SoTien DECIMAL(18,0) NOT NULL,
    MaKT VARCHAR(10) NOT NULL,
    CONSTRAINT FK_PhieuChi_MaKT FOREIGN KEY (MaKT) REFERENCES QuyetDinhKhenThuong(MaKT),
    CONSTRAINT UQ_PhieuChi_MaKT UNIQUE (MaKT),
    CONSTRAINT CK_PC_Tien CHECK (SoTien > 0)
);

CREATE TABLE QuyetDinhKyLuat (
    MaKL VARCHAR(10) NOT NULL PRIMARY KEY,
    NgayQD DATE NOT NULL,
    HinhThuc NVARCHAR(30) NOT NULL,
    LyDo NVARCHAR(200) NULL,
    SoTienPhat DECIMAL(18,0) NOT NULL,
    MaNV VARCHAR(10) NOT NULL,
    CONSTRAINT FK_QuyetDinhKyLuat_MaNV FOREIGN KEY (MaNV) REFERENCES NhanVien(MaNV),
    CONSTRAINT CK_KL_HinhThuc CHECK (HinhThuc IN (N'Khiển trách', N'Cảnh cáo', N'Phạt tiền')),
    CONSTRAINT CK_KL_Phat CHECK ((HinhThuc = N'Phạt tiền' AND SoTienPhat > 0) OR (HinhThuc <> N'Phạt tiền' AND SoTienPhat = 0))
);

CREATE TABLE PhieuThu (
    MaPT VARCHAR(10) NOT NULL PRIMARY KEY,
    NgayThu DATE NOT NULL,
    SoTien DECIMAL(18,0) NOT NULL,
    MaKL VARCHAR(10) NOT NULL,
    CONSTRAINT FK_PhieuThu_MaKL FOREIGN KEY (MaKL) REFERENCES QuyetDinhKyLuat(MaKL),
    CONSTRAINT UQ_PhieuThu_MaKL UNIQUE (MaKL),
    CONSTRAINT CK_PT_Tien CHECK (SoTien > 0)
);

CREATE TABLE BangLuong (
    MaBL VARCHAR(10) NOT NULL PRIMARY KEY,
    Thang INT NOT NULL,
    Nam INT NOT NULL,
    LuongCoBan DECIMAL(18,0) NOT NULL,
    PhuCap DECIMAL(18,0) NOT NULL,
    TienPhuTroi DECIMAL(18,0) NOT NULL,
    TienThuong DECIMAL(18,0) NOT NULL,
    TienBaoHiem DECIMAL(18,0) NOT NULL,
    TienPhat DECIMAL(18,0) NOT NULL,
    ThucLanh DECIMAL(18,0) NOT NULL,
    MaNV VARCHAR(10) NOT NULL,
    CONSTRAINT FK_BangLuong_MaNV FOREIGN KEY (MaNV) REFERENCES NhanVien(MaNV),
    CONSTRAINT CK_BL_Thang CHECK (Thang BETWEEN 1 AND 12),
    CONSTRAINT UQ_BL UNIQUE (MaNV, Thang, Nam)
);

GO