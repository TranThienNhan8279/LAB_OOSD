IF DB_ID(N'QuanLyBenhAn') IS NOT NULL
BEGIN
    ALTER DATABASE QuanLyBenhAn SET SINGLE_USER WITH ROLLBACK IMMEDIATE;
    DROP DATABASE QuanLyBenhAn;
END
GO
CREATE DATABASE QuanLyBenhAn;
GO
USE QuanLyBenhAn;
GO

CREATE TABLE BenhNhan (
    MaBN VARCHAR(10) NOT NULL PRIMARY KEY,
    HoTen NVARCHAR(100) NOT NULL,
    DiaChi NVARCHAR(200) NULL,
    NgaySinh DATE NOT NULL,
    DienThoai VARCHAR(15) NULL,
    AnhChup NVARCHAR(200) NULL
);

CREATE TABLE PhieuDangKy (
    MaPhieuDK VARCHAR(10) NOT NULL PRIMARY KEY,
    NgayDangKy DATE NOT NULL,
    MaBN VARCHAR(10) NOT NULL,
    CONSTRAINT FK_PhieuDangKy_MaBN FOREIGN KEY (MaBN) REFERENCES BenhNhan(MaBN),
    CONSTRAINT UQ_PhieuDangKy_MaBN UNIQUE (MaBN)
);

CREATE TABLE LePhi (
    MaLePhi VARCHAR(10) NOT NULL PRIMARY KEY,
    Nam INT NOT NULL,
    SoTien DECIMAL(18,0) NOT NULL,
    NgayDong DATE NOT NULL,
    MaBN VARCHAR(10) NOT NULL,
    CONSTRAINT FK_LePhi_MaBN FOREIGN KEY (MaBN) REFERENCES BenhNhan(MaBN),
    CONSTRAINT CK_LePhi CHECK (SoTien > 0),
    CONSTRAINT UQ_LePhi_Nam UNIQUE (MaBN, Nam)
);

CREATE TABLE HoSoBenhAn (
    MaHoSo VARCHAR(10) NOT NULL PRIMARY KEY,
    NgayCap DATE NOT NULL,
    MaBN VARCHAR(10) NOT NULL,
    CONSTRAINT FK_HoSoBenhAn_MaBN FOREIGN KEY (MaBN) REFERENCES BenhNhan(MaBN),
    CONSTRAINT UQ_HoSoBenhAn_MaBN UNIQUE (MaBN)
);

CREATE TABLE Khoa (
    MaKhoa VARCHAR(10) NOT NULL PRIMARY KEY,
    TenKhoa NVARCHAR(100) NOT NULL
);

CREATE TABLE BacSi (
    MaBS VARCHAR(10) NOT NULL PRIMARY KEY,
    HoTen NVARCHAR(100) NOT NULL,
    ChuyenMon NVARCHAR(100) NOT NULL,
    MaKhoa VARCHAR(10) NOT NULL,
    CONSTRAINT FK_BacSi_MaKhoa FOREIGN KEY (MaKhoa) REFERENCES Khoa(MaKhoa)
);

CREATE TABLE NhanVien (
    MaNV VARCHAR(10) NOT NULL PRIMARY KEY,
    HoTen NVARCHAR(100) NOT NULL,
    ChucVu NVARCHAR(100) NOT NULL
);

CREATE TABLE PhieuKham (
    MaPhieuKham VARCHAR(10) NOT NULL PRIMARY KEY,
    NgayGioKham DATETIME NOT NULL,
    TrieuChung NVARCHAR(200) NULL,
    ThanNhiet DECIMAL(5,2) NOT NULL,
    HuyetAp NVARCHAR(100) NULL,
    LoaiKham NVARCHAR(30) NOT NULL,
    TrangThai NVARCHAR(30) NOT NULL,
    MaHoSo VARCHAR(10) NOT NULL,
    MaBS VARCHAR(10) NOT NULL,
    MaKhoa VARCHAR(10) NOT NULL,
    MaNVGhiNhan VARCHAR(10) NULL,
    CONSTRAINT FK_PhieuKham_MaHoSo FOREIGN KEY (MaHoSo) REFERENCES HoSoBenhAn(MaHoSo),
    CONSTRAINT FK_PhieuKham_MaBS FOREIGN KEY (MaBS) REFERENCES BacSi(MaBS),
    CONSTRAINT FK_PhieuKham_MaKhoa FOREIGN KEY (MaKhoa) REFERENCES Khoa(MaKhoa),
    CONSTRAINT FK_PhieuKham_MaNVGhiNhan FOREIGN KEY (MaNVGhiNhan) REFERENCES NhanVien(MaNV),
    CONSTRAINT CK_PhieuKham_Loai CHECK (LoaiKham IN (N'Điều trị', N'Định kỳ')),
    CONSTRAINT CK_PhieuKham_TT CHECK (TrangThai IN (N'Đang điều trị', N'Hoàn tất'))
);

CREATE TABLE Thuoc (
    MaThuoc VARCHAR(10) NOT NULL PRIMARY KEY,
    TenThuoc NVARCHAR(100) NOT NULL,
    DonViTinh NVARCHAR(100) NOT NULL
);

CREATE TABLE ToaThuoc (
    MaToa VARCHAR(10) NOT NULL PRIMARY KEY,
    NgayLap DATE NOT NULL,
    LoiDan NVARCHAR(200) NULL,
    MaPhieuKham VARCHAR(10) NOT NULL,
    CONSTRAINT FK_ToaThuoc_MaPhieuKham FOREIGN KEY (MaPhieuKham) REFERENCES PhieuKham(MaPhieuKham),
    CONSTRAINT UQ_ToaThuoc_MaPhieuKham UNIQUE (MaPhieuKham)
);

CREATE TABLE ChiTietToaThuoc (
    MaCTT VARCHAR(10) NOT NULL PRIMARY KEY,
    SoLuong INT NOT NULL,
    LieuDung NVARCHAR(200) NOT NULL,
    MaToa VARCHAR(10) NOT NULL,
    MaThuoc VARCHAR(10) NOT NULL,
    CONSTRAINT FK_ChiTietToaThuoc_MaToa FOREIGN KEY (MaToa) REFERENCES ToaThuoc(MaToa) ON DELETE CASCADE,
    CONSTRAINT FK_ChiTietToaThuoc_MaThuoc FOREIGN KEY (MaThuoc) REFERENCES Thuoc(MaThuoc),
    CONSTRAINT CK_CTT_SL CHECK (SoLuong > 0),
    CONSTRAINT UQ_CTT UNIQUE (MaToa, MaThuoc)
);

CREATE TABLE LoaiXetNghiem (
    MaLoaiXN VARCHAR(10) NOT NULL PRIMARY KEY,
    TenXN NVARCHAR(100) NOT NULL
);

CREATE TABLE XetNghiem (
    MaXN VARCHAR(10) NOT NULL PRIMARY KEY,
    NgayXN DATE NOT NULL,
    KetQua NVARCHAR(200) NULL,
    MaPhieuKham VARCHAR(10) NOT NULL,
    MaLoaiXN VARCHAR(10) NOT NULL,
    CONSTRAINT FK_XetNghiem_MaPhieuKham FOREIGN KEY (MaPhieuKham) REFERENCES PhieuKham(MaPhieuKham) ON DELETE CASCADE,
    CONSTRAINT FK_XetNghiem_MaLoaiXN FOREIGN KEY (MaLoaiXN) REFERENCES LoaiXetNghiem(MaLoaiXN)
);

CREATE TABLE ThanhToanVienPhi (
    MaTT VARCHAR(10) NOT NULL PRIMARY KEY,
    NgayThanhToan DATE NOT NULL,
    SoTien DECIMAL(18,0) NOT NULL,
    NgayXuatVien DATE NOT NULL,
    MaPhieuKham VARCHAR(10) NOT NULL,
    CONSTRAINT FK_ThanhToanVienPhi_MaPhieuKham FOREIGN KEY (MaPhieuKham) REFERENCES PhieuKham(MaPhieuKham),
    CONSTRAINT UQ_ThanhToanVienPhi_MaPhieuKham UNIQUE (MaPhieuKham),
    CONSTRAINT CK_TT_Tien CHECK (SoTien >= 0)
);

CREATE TABLE LichKhamDinhKy (
    MaLich VARCHAR(10) NOT NULL PRIMARY KEY,
    Quy INT NOT NULL,
    Nam INT NOT NULL,
    NgayHen DATETIME NOT NULL,
    TrangThai NVARCHAR(30) NOT NULL,
    MaHoSo VARCHAR(10) NOT NULL,
    CONSTRAINT FK_LichKhamDinhKy_MaHoSo FOREIGN KEY (MaHoSo) REFERENCES HoSoBenhAn(MaHoSo),
    CONSTRAINT CK_Lich_Quy CHECK (Quy BETWEEN 1 AND 4),
    CONSTRAINT UQ_Lich_Quy UNIQUE (MaHoSo, Quy, Nam),
    CONSTRAINT CK_Lich_TT CHECK (TrangThai IN (N'Đã hẹn', N'Đã khám'))
);

GO